import { describe, it, beforeEach } from 'node:test';
import assert from 'node:assert/strict';
import QRCode from 'qrcode';
import jsQR from 'jsqr';
import {
  createTransferChunks,
  decompressTransferData,
  getCouponsForDate,
  isoToEpochDays,
  loadCoupons,
  mergeCoupons,
  parseCouponPayload,
  parseTransferChunk,
  type MealType,
} from '../src/lib/storage.ts';

function installMockLocalStorage(): Map<string, string> {
  const store = new Map<string, string>();
  Object.defineProperty(globalThis, 'localStorage', {
    configurable: true,
    value: {
      getItem: (key: string) => (store.has(key) ? store.get(key)! : null),
      setItem: (key: string, value: string) => {
        store.set(key, String(value));
      },
      removeItem: (key: string) => {
        store.delete(key);
      },
    },
  });
  return store;
}

/**
 * Generates an actual QR code matrix via `qrcode` and rasterizes it into an
 * RGBA pixel buffer suitable for decoding by `jsQR`.
 */
function renderQrToRgba(
  text: string,
  scale = 6,
  margin = 4
): { data: Uint8ClampedArray; width: number; height: number } {
  const qr = QRCode.create(text, { errorCorrectionLevel: 'M' });
  const modules = qr.modules;
  const size = modules.size;
  const totalModules = size + margin * 2;
  const width = totalModules * scale;
  const height = width;
  const data = new Uint8ClampedArray(width * height * 4);

  // Fill pure white background
  data.fill(255);

  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) {
      if (!modules.get(row, col)) continue;
      const startX = (col + margin) * scale;
      const startY = (row + margin) * scale;
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          const idx = ((startY + dy) * width + (startX + dx)) * 4;
          data[idx] = 0;
          data[idx + 1] = 0;
          data[idx + 2] = 0;
          data[idx + 3] = 255;
        }
      }
    }
  }

  return { data, width, height };
}

describe('QR Code Generation (qrcode) + Camera Decoding (jsQR)', () => {
  beforeEach(() => {
    installMockLocalStorage();
  });

  it('encodes and decodes individual mess coupon QR payloads losslessly', async () => {
    const payload = 'MESS-88412`Nov 22, 2026';

    // Also verify SVG output generated by the Pass Card view
    const svg = await QRCode.toString(payload, {
      type: 'svg',
      margin: 2,
      errorCorrectionLevel: 'M',
    });
    assert.ok(svg.includes('<svg') && svg.includes('</svg>'));

    // Rasterize and decode via jsQR (simulating scanning the rendered pass)
    const img = renderQrToRgba(payload);
    const decoded = jsQR(img.data, img.width, img.height, {
      inversionAttempts: 'attemptBoth',
    });
    assert.ok(decoded, 'jsQR should decode generated coupon QR');
    assert.equal(decoded.data, payload);

    const parsed = parseCouponPayload(decoded.data);
    assert.ok(parsed);
    assert.equal(parsed.id, 'MESS-88412');
    assert.equal(parsed.dateISO, '2026-11-22');
    assert.equal(parsed.displayDate, 'Nov 22, 2026');
  });

  it('simulates camera scanner meal tagging (Auto vs explicit Breakfast/Lunch/Dinner)', () => {
    const payload = 'CAM-77`Nov 25, 2026';
    const img = renderQrToRgba(payload);
    const decoded = jsQR(img.data, img.width, img.height);
    assert.ok(decoded);
    const parsed = parseCouponPayload(decoded.data)!;

    // Scan 1: Auto mode stores as U
    mergeCoupons([{ epochDays: parsed.epochDays, meal: 'U', id: parsed.id }], {
      overwriteKnownMeal: false,
    });
    assert.equal(getCouponsForDate('2026-11-25')[0].meal, 'U');

    // Scan 2: Explicit Lunch tag upgrades U -> L
    mergeCoupons([{ epochDays: parsed.epochDays, meal: 'L', id: parsed.id }], {
      overwriteKnownMeal: true,
    });
    assert.equal(getCouponsForDate('2026-11-25')[0].meal, 'L');

    // Scan 3: Auto mode again preserves existing L
    mergeCoupons([{ epochDays: parsed.epochDays, meal: 'U', id: parsed.id }], {
      overwriteKnownMeal: false,
    });
    assert.equal(getCouponsForDate('2026-11-25')[0].meal, 'L');

    // Scan 4: Explicit Dinner tag re-tags L -> D
    mergeCoupons([{ epochDays: parsed.epochDays, meal: 'D', id: parsed.id }], {
      overwriteKnownMeal: true,
    });
    assert.equal(getCouponsForDate('2026-11-25')[0].meal, 'D');
  });

  it('transfers 120 coupons across devices via multi-chunk MC1 QR images scanned out of order', () => {
    // Device A: populate 120 coupons (~40 days x 3 meals)
    const startEpoch = isoToEpochDays('2026-11-01')!;
    const meals: MealType[] = ['B', 'L', 'D'];
    mergeCoupons(
      Array.from({ length: 120 }, (_, i) => ({
        epochDays: startEpoch + Math.floor(i / 3),
        meal: meals[i % 3],
        id: `TX${String(5000 + i)}`,
      }))
    );

    const deviceACoupons = loadCoupons();
    assert.equal(deviceACoupons.length, 120);

    const chunks = createTransferChunks(280);
    assert.ok(chunks.length >= 2, `Expected multi-chunk transfer, got ${chunks.length}`);

    // Render every chunk as a real QR image
    const qrFrames = chunks.map((chunkText) => renderQrToRgba(chunkText, 5, 4));

    // Device B: fresh empty storage, scan QR frames out of order (even indices, then odd)
    installMockLocalStorage();
    assert.equal(loadCoupons().length, 0);

    const scanOrder = [
      ...qrFrames.map((_, i) => i).filter((i) => i % 2 === 1),
      ...qrFrames.map((_, i) => i).filter((i) => i % 2 === 0),
    ];

    let rxTotal = 0;
    const rxParts = new Map<number, string>();

    for (const frameIdx of scanOrder) {
      const frame = qrFrames[frameIdx];
      const qr = jsQR(frame.data, frame.width, frame.height, {
        inversionAttempts: 'attemptBoth',
      });
      assert.ok(qr, `jsQR failed to decode transfer chunk frame #${frameIdx + 1}`);

      const parsedChunk = parseTransferChunk(qr.data);
      assert.ok(parsedChunk);
      rxTotal = parsedChunk.total;
      rxParts.set(parsedChunk.part, parsedChunk.data);
    }

    assert.equal(rxParts.size, rxTotal);
    let joined = '';
    for (let p = 1; p <= rxTotal; p++) {
      joined += rxParts.get(p)!;
    }

    const decodedCoupons = decompressTransferData(joined);
    assert.ok(decodedCoupons);
    const merged = mergeCoupons(decodedCoupons);
    assert.equal(merged.added, 120);
    assert.deepEqual(loadCoupons(), deviceACoupons);
  });
});
